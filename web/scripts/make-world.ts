/**
 * Regenerates src/lib/world.ts: the Natural Earth 1:110m land outline (public domain) as one
 * SVG path in a 360 × 180 plate carrée frame (x = lon + 180, y = 90 − lat).
 *
 *   npm pack world-atlas@2.0.2 && tar xzf world-atlas-2.0.2.tgz
 *   node scripts/make-world.ts package/land-110m.json > src/lib/world.ts
 */
import { readFileSync } from 'node:fs';

// A ring is a list of arc indices; a polygon is a list of rings.
type Geometry =
	{ type: 'Polygon'; arcs: number[][] } | { type: 'MultiPolygon'; arcs: number[][][] };
type Topology = {
	transform: { scale: [number, number]; translate: [number, number] };
	arcs: [number, number][][];
	objects: { land: { geometries: Geometry[] } };
};

const topo = JSON.parse(readFileSync(process.argv[2], 'utf8')) as Topology;
const [sx, sy] = topo.transform.scale;
const [tx, ty] = topo.transform.translate;

const decoded = topo.arcs.map((arc) => {
	let x = 0;
	let y = 0;
	return arc.map(([dx, dy]) => {
		x += dx;
		y += dy;
		return [x * sx + tx, y * sy + ty] as [number, number];
	});
});

const arcPoints = (i: number) => (i >= 0 ? decoded[i] : [...decoded[~i]].reverse());
const round = (v: number) => Math.round(v * 10) / 10;

const rings: string[] = [];
const toPath = (points: [number, number][], shift: number) => {
	let last = '';
	const parts: string[] = [];
	for (const [x, y] of points) {
		const p = `${round(x + shift)} ${round(y)}`;
		if (p !== last) parts.push(p);
		last = p;
	}
	return parts.length > 2 ? `M${parts.join('L')}Z` : '';
};
for (const geometry of topo.objects.land.geometries) {
	const polygons = geometry.type === 'Polygon' ? [geometry.arcs] : geometry.arcs;
	for (const polygon of polygons)
		for (const ring of polygon) {
			const lonLat = ring.flatMap((i, n) => arcPoints(i).slice(n === 0 ? 0 : 1));
			// Unwrap longitudes so rings crossing the antimeridian stay continuous (x may leave
			// 0..360), then draw a shifted copy; the SVG viewBox clips what falls outside.
			const points: [number, number][] = [];
			let offset = 0;
			let prev: number | null = null;
			for (const [lon, lat] of lonLat) {
				if (prev !== null && Math.abs(lon - prev) > 180) offset += lon < prev ? 360 : -360;
				prev = lon;
				points.push([lon + offset + 180, 90 - lat]);
			}
			const xs = points.map((p) => p[0]);
			rings.push(toPath(points, 0));
			if (Math.max(...xs) > 360) rings.push(toPath(points, -360));
			if (Math.min(...xs) < 0) rings.push(toPath(points, 360));
		}
}

console.log(`/* Generated by scripts/make-world.ts — do not edit.
 * Land outline from Natural Earth 1:110m (public domain), via world-atlas 2.0.2 (ISC).
 * Plate carrée in a 360 × 180 frame: x = longitude + 180, y = 90 − latitude. */
export const LAND_PATH =
\t'${rings.join('')}';`);
